import { index, pgTable, text, timestamp } from 'drizzle-orm/pg-core';

/**
 * Что разрешает пропуск. Областей две, и они для разных людей: `formats` — организатору,
 * собирать форматы турниров, `roster` — игроку, заявлять свой состав на текущий турнир.
 *
 * Разделены намеренно. Ссылка — это и есть право, и пропуск игрока не должен открывать
 * настройки сервера просто потому, что оба живут в одной таблице.
 */
export type WebGrantScope = 'formats' | 'roster';

/**
 * Пропуск на витрину — способ дать право что-то менять человеку, который на сайт не входил.
 *
 * Витрина по устройству анонимна и только для чтения: ни логина, ни пароля, ни OAuth. Это
 * не пробел, а решение — заводить второй способ доказать, кто ты, когда Discord уже знает
 * это про всех, значит держать два списка людей и однажды их разойти.
 *
 * Поэтому право приходит ссылкой. Бот выдаёт её в личные сообщения тому, у кого право уже
 * есть по правам Discord, а страница верит неугадываемому токену в адресе. Тот же приём уже
 * работает для драфта, где токен пускает капитана банить за свою команду; здесь он пускает
 * организатора собирать форматы турниров.
 *
 * Что из этого следует и о чём надо помнить: ссылка — это и есть право. Переслать её значит
 * передать доступ. Отсюда два свойства таблицы: у пропуска есть срок, и на человека с одной
 * областью он один — выдача новой ссылки гасит прежнюю, поэтому «отозвать» всегда возможно.
 */
export const webGrants = pgTable(
  'web_grants',
  {
    /** Сам токен. Он же первичный ключ: искать пропуск всегда приходят с ним. */
    token: text('token').primaryKey(),
    guildId: text('guild_id').notNull(),
    userId: text('user_id').notNull(),
    /**
     * Что именно разрешает пропуск. Область записана в самом пропуске, а не выводится из
     * прав Discord при каждом запросе: право могли отобрать после выдачи, и тогда ссылка
     * обязана перестать работать — но проверять это походом в Discord на каждый нажатый
     * переключатель значило бы ставить страницу в зависимость от его доступности.
     * Компромисс — короткий срок жизни пропуска.
     */
    scope: text('scope').$type<WebGrantScope>().notNull(),
    expiresAt: timestamp('expires_at', { withTimezone: true }).notNull(),
    createdAt: timestamp('created_at', { withTimezone: true }).notNull().defaultNow(),
  },
  (table) => [index('web_grants_owner_idx').on(table.guildId, table.userId, table.scope)],
);

export type WebGrantRow = typeof webGrants.$inferSelect;
