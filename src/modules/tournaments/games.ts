import type { TournamentGame } from './schema.js';

/**
 * Дисциплины: те, по которым турниры проводят **сейчас**, и те, которые бот обязан
 * по-прежнему понимать.
 *
 * Это два разных списка, и разделены они нарочно. Сузить один список до трёх дисциплин и на
 * этом закончить было бы ошибкой: в базе лежат прошлые турниры по League of Legends и TFT, у
 * игроков есть подтверждённые привязки к ним, а в зале славы — титулы. Витрина и лидерборды
 * обязаны их читать, иначе прошлое сервера превращается в «неизвестная дисциплина».
 *
 * Поэтому предлагаемых дисциплин три, а понимаемых — пять.
 */

/**
 * Что предлагается при создании турнира и в ежедневном голосовании.
 *
 * Порядок фиксированный и уходит в варианты нативного голосования Discord как есть: индекс
 * дисциплины здесь становится индексом ответа опроса. На согласованность прошлых голосований
 * это уже не влияет — `tournament_polls.options` хранит свой список у каждого опроса, и
 * подсчёт в finalizer.ts читает его, а не эту константу. Именно поэтому список можно менять.
 */
export const TOURNAMENT_GAMES: readonly TournamentGame[] = ['dota2', 'valorant', 'genshin'];

/**
 * Все дисциплины, которые бот понимает, включая те, по которым больше не играют.
 *
 * Нужен там, где речь о прошлом: арт и подписи для страницы старого турнира, обход всех
 * лидербордов, проверки целостности. Убирать отсюда дисциплину можно только вместе с её
 * историей, а история — то, ради чего бот и заводился.
 */
export const KNOWN_TOURNAMENT_GAMES: readonly TournamentGame[] = [
  'dota2',
  'lol',
  'tft',
  'valorant',
  'genshin',
];

export const TOURNAMENT_GAME_LABELS: Record<TournamentGame, string> = {
  dota2: 'Dota 2',
  lol: 'League of Legends',
  tft: 'Teamfight Tactics',
  valorant: 'Valorant',
  genshin: 'Genshin Impact',
};
