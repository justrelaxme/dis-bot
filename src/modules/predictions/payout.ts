/**
 * Награда за угаданный матч.
 *
 * **Прогноз, а не ставка.** Участник ничего не вносит: он называет победителя и получает
 * монеты, если угадал. Ставка с внесением означала бы путь списания, а значит и возможность
 * уйти в минус, и гонку между двумя одновременными ставками на один баланс — три новых способа
 * сломаться ради механики, которой на игровом сервере хватает и без денег. Не угадал — просто
 * ноль, без потерь.
 *
 * Платит больше тот исход, который назвали немногие. Иначе все ставят на фаворита, награда
 * достаётся всем поровну и угадывать становится незачем: смысл прогноза в том, чтобы решиться
 * назвать неочевидное.
 */

/** Базовая награда за угаданный матч, когда мнения разделились ровно. */
export const BASE_REWARD = 10;

/**
 * Предел множителя. Без него единственный угадавший из сотни получал бы тысячу базовых наград
 * за один матч — больше, чем даёт победа в турнире, и тогда играть выгоднее не играя.
 */
export const MAX_MULTIPLIER = 5;

export interface PayoutInput {
  /** Совпал ли прогноз с настоящим победителем. */
  correct: boolean;
  /** Сколько человек назвали тот же исход, включая самого прогнозиста. */
  votesForPick: number;
  /** Сколько человек дали прогноз на этот матч вообще. */
  votesTotal: number;
  /** Базовая награда. Вынесена параметром, чтобы её можно было настроить, не правя правило. */
  base?: number;
}

/**
 * Сколько монет причитается. Ноль за неугаданное — и ноль это полноценный исход, а не признак
 * ошибки: прогноз бесплатный, и не угадавший ничего не теряет.
 */
export function predictionPayout(input: PayoutInput): number {
  if (!input.correct) return 0;
  if (input.votesForPick < 1 || input.votesTotal < 1) return 0;

  const base = input.base ?? BASE_REWARD;
  // Чем меньше доля угадавших, тем больше множитель. Один из десяти получает пятикратную
  // награду (упёрся в предел), пять из десяти — двойную, все десять — одинарную.
  const multiplier = Math.min(MAX_MULTIPLIER, input.votesTotal / input.votesForPick);
  return Math.round(base * multiplier);
}

/**
 * Как назвать точность прогнозиста. Проценты без числа попыток обманчивы: «100%» с одной
 * угадкой и «70%» с сорока — разные вещи, и показывать надо обе цифры.
 */
export function accuracy(correct: number, total: number): number {
  if (total <= 0) return 0;
  return Math.round((correct / total) * 100);
}
