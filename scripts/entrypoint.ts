/**
 * Точка входа контейнера: сначала миграции, потом бот.
 *
 * Нужна для платформ, где контейнер один и отдельного шага миграций нет — там код и база
 * обновляются одним деплоем, и бот, запущенный раньше миграций, упадёт на первом же
 * запросе к новой колонке. В docker-compose миграции выполняет отдельный одноразовый
 * сервис, и повторный прогон здесь ничего не делает: drizzle применяет только то, чего в
 * `__drizzle_migrations` ещё нет.
 *
 * Миграции запускаются отдельным процессом, а не импортом: провалившийся импорт оставил бы
 * половину состояния в этом же процессе, а бот всё равно не должен стартовать после
 * неудачной миграции — код возврата здесь и есть это решение.
 */
import { spawnSync } from 'node:child_process';

const migrate = spawnSync(process.execPath, ['dist/scripts/migrate.js'], { stdio: 'inherit' });

if (migrate.error) {
  process.stderr.write(`не удалось запустить миграции: ${migrate.error.message}\n`);
  process.exit(1);
}
if (migrate.status !== 0) {
  process.stderr.write('миграции не применились — бот не стартует\n');
  process.exit(migrate.status ?? 1);
}

await import('../src/index.js');
